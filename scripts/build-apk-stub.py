#!/usr/bin/env python3
"""Build the pre-bundled VOLT-SPECTRA Android release artifact.

The GitHub Actions pipeline (build-and-bundle-apk.yml) produces the real
signed APK and copies it to ``public/releases/voltspectra-release.apk``.  This
script generates a deterministic, pre-bundled distribution stub so the
One-Tap download button never 404s on a fresh Vercel deployment before the
first CI run has completed.

The stub is a valid ZIP archive (APK == ZIP) carrying the release manifest,
checksum and the polyglot build spec.  It is replaced automatically by the
pipeline's signed artifact.
"""
from __future__ import annotations

import hashlib
import io
import json
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "public" / "releases" / "voltspectra-release.apk"

MANIFEST = {
    "name": "VoltSpectra",
    "package": "com.voltspectra.griddsp",
    "version": "1.0.0",
    "versionCode": 1,
    "arch": "arm64-v8a",
    "minSdk": 24,
    "targetSdk": 34,
    "languages": ["Angular 19 Signals", "ANSI C99 DSP", "Ruby 3.3", "GraphQL SDL", "GLSL ES 3.00"],
    "offlineReady": True,
    "stub": True,
    "note": (
        "This is the pre-bundled distribution placeholder. The signed release "
        "APK is produced by .github/workflows/build-and-bundle-apk.yml and "
        "overwrites this file. Sideload the CI artifact for a runnable build."
    ),
}

FILES = {
    "README.txt": (
        "VOLT-SPECTRA v1.0.0-arm64 — pre-bundled distribution stub\n"
        "==========================================================\n\n"
        "Package : com.voltspectra.griddsp\n"
        "Stack   : Angular 19 Signals + ANSI C99 DSP + Ruby 3.3 + GraphQL SDL + GLSL\n"
        "Offline : 100% blackout / basement / off-grid ready\n\n"
        "The signed APK is generated by the GitHub Actions pipeline and replaces\n"
        "this stub at public/releases/voltspectra-release.apk.\n"
    ),
    "META-INF/MANIFEST.MF": (
        "Manifest-Version: 1.0\r\n"
        "Created-By: VOLT-SPECTRA build-apk-stub.py\r\n"
        "Package: com.voltspectra.griddsp\r\n"
        "Version: 1.0.0\r\n\r\n"
    ),
    "AndroidManifest.xml": (
        "<!-- placeholder manifest; the CI pipeline bundles the real binary AXML -->\n"
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<manifest xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    package="com.voltspectra.griddsp" android:versionCode="1" android:versionName="1.0.0">\n'
        '  <application android:label="VoltSpectra" />\n'
        '</manifest>\n'
    ),
    "assets/release-manifest.json": json.dumps(MANIFEST, indent=2) + "\n",
    "assets/release-notes.txt": (
        "Sweep power strips for vampire loads, measure grid frequency / THD,\n"
        "time your smart-meter LED and shift heavy loads off the surge window.\n"
    ),
    "classes.dex": "DEX\n035\0" + "VOLT-SPECTRA-distribution-stub" + "\0",
    "res/values/strings.xml": (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<resources><string name="app_name">VoltSpectra</string></resources>\n'
    ),
}


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for name, content in FILES.items():
            zf.writestr(name, content)
    data = buf.getvalue()
    OUT.write_bytes(data)
    digest = hashlib.sha256(data).hexdigest()
    print(f"[build-apk-stub] wrote {OUT} ({len(data)} bytes)")
    print(f"[build-apk-stub] sha256 {digest}")


if __name__ == "__main__":
    main()
