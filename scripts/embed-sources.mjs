/**
 * Deterministic polyglot source embedder.
 *
 * Reads the canonical five-language sources and emits a single typed
 * TypeScript module (`src/generated/embedded-sources.ts`) so the in-app
 * Polyglot Inspector and the WebGL2 plasma renderer can consume the *real*
 * files without relying on bundler-specific `?raw` loader semantics.
 *
 * This keeps `npm run build` 100% deterministic on Vercel (no clang / emcc).
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

/** export name -> repository-relative file path */
const SOURCES = {
  C99_HARMONIC_SOURCE: 'c-dsp/electromagnetic_harmonic.c',
  RUBY_TARIFF_SOURCE: 'api/tariff_auditor.rb',
  GRAPHQL_SDL: 'src/graphql/grid_telemetry.graphql',
  GLSL_PLASMA_SOURCE: 'src/shaders/plasma_field.glsl',
  CAPACITOR_CONFIG: 'capacitor.config.ts',
  APK_WORKFLOW: '.github/workflows/build-and-bundle-apk.yml',
  DSP_BRIDGE_SOURCE: 'src/wasm/c99HarmonicBridge.ts',
};

function readSource(relPath) {
  const abs = join(root, relPath);
  if (!existsSync(abs)) return '';
  try {
    return readFileSync(abs, 'utf8');
  } catch {
    return '';
  }
}

function sha256(file) {
  if (!existsSync(file)) return 'missing';
  return createHash('sha256').update(readFileSync(file)).digest('hex');
}

const emitted = Object.fromEntries(
  Object.entries(SOURCES).map(([key, rel]) => [key, readSource(rel)]),
);

const apkPath = join(root, 'public/releases/voltspectra-release.apk');
const apkSha = sha256(apkPath);
const apkSize = existsSync(apkPath) ? readFileSync(apkPath).length : 0;

const banner = `/* eslint-disable */
// AUTO-GENERATED by scripts/embed-sources.mjs — do not edit by hand.
// Regenerate with: npm run embed
`;

const body = [
  banner,
  `export const APK_SHA256 = ${JSON.stringify(apkSha)};`,
  `export const APK_SIZE_BYTES = ${apkSize};`,
  `export const EMBEDDED_AT = ${JSON.stringify(new Date().toISOString())};`,
  '',
];

for (const [key, value] of Object.entries(emitted)) {
  body.push(`export const ${key} = ${JSON.stringify(value)};`);
}

const outDir = join(root, 'src/generated');
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'embedded-sources.ts'), body.join('\n') + '\n');

console.log(
  `[embed-sources] wrote src/generated/embedded-sources.ts ` +
    `(${Object.values(emitted).reduce((n, s) => n + s.length, 0)} chars, apk sha256=${apkSha.slice(0, 12)}…)`,
);
